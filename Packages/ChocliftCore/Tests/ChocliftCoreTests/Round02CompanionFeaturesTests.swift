final class Round02CompanionFeaturesTests: XCTestCase {

    // MARK: - 1. Clipboard Truncation at 280 Characters & Non-Text / Sensitive Filtering

    func testClipboardTruncationAt280CharactersAndEmojiSafety() throws {
        let shortText = "git status && swift test"
        let shortEval = ClipboardPreviewEvaluator.evaluate(
            pasteboardTypes: ["public.utf8-plain-text"],
            string: shortText
        )
        XCTAssertEqual(shortEval.previewText, shortText)
        XCTAssertFalse(shortEval.isTruncated)
        XCTAssertTrue(shortEval.hasText)

        // Exact 280-character boundary: not truncated
        let exact280 = String(repeating: "A", count: 280)
        let exactEval = ClipboardPreviewEvaluator.evaluate(
            pasteboardTypes: ["public.utf8-plain-text"],
            string: exact280
        )
        XCTAssertEqual(exactEval.previewText?.count, 280)
        XCTAssertEqual(exactEval.previewText, exact280)
        XCTAssertFalse(exactEval.isTruncated)

        // 281 characters: truncated to 280 characters
        let over281 = exact280 + "Z"
        let overEval = ClipboardPreviewEvaluator.evaluate(
            pasteboardTypes: ["public.utf8-plain-text"],
            string: over281
        )
        XCTAssertEqual(overEval.previewText?.count, 280)
        XCTAssertEqual(overEval.previewText, exact280)
        XCTAssertTrue(overEval.isTruncated)

        // Multi-scalar emoji grapheme clusters: truncated cleanly at 280 Character boundary
        let emojiSource = String(repeating: "👨‍👩‍👧‍👦", count: 310)
        let emojiEval = ClipboardPreviewEvaluator.evaluate(
            pasteboardTypes: ["public.utf8-plain-text"],
            string: emojiSource
        )
        XCTAssertEqual(emojiEval.previewText?.count, 280)
        XCTAssertTrue(emojiEval.isTruncated)

        // Insertable text preserves full plain text (up to snippet body limit) for Mac cursor paste
        let fullInsertable = ClipboardPreviewEvaluator.extractInsertablePlainText(
            pasteboardTypes: ["public.utf8-plain-text"],
            string: over281
        )
        XCTAssertEqual(fullInsertable, over281)

        // Codable wire defense: even if raw JSON contains >280 chars, decoding clamps to 280 chars
        let oversizedRawJSON = Data("{\"previewText\":\"\(String(repeating: "X", count: 400))\",\"isTruncated\":false}".utf8)
        let decoded = try JSONDecoder().decode(ClipboardPreviewSnapshot.self, from: oversizedRawJSON)
        XCTAssertEqual(decoded.previewText?.count, 280)
        XCTAssertTrue(decoded.isTruncated)
    }

    func testNonTextAndSensitiveClipboardsProduceEmptyState() {
        // 1. Empty pasteboard
        XCTAssertEqual(
            ClipboardPreviewEvaluator.evaluate(pasteboardTypes: [], string: nil),
            .empty
        )
        XCTAssertEqual(
            ClipboardPreviewEvaluator.evaluate(pasteboardTypes: ["public.utf8-plain-text"], string: "   \n\t "),
            .empty
        )
        XCTAssertNil(
            ClipboardPreviewEvaluator.extractInsertablePlainText(pasteboardTypes: ["public.utf8-plain-text"], string: "  \n ")
        )

        // 2. Images / PDFs produce quiet empty state even if NSPasteboard provides a fallback string
        for imageType in ["public.png", "public.tiff", "public.jpeg", "public.heic", "com.adobe.pdf"] {
            let snapshot = ClipboardPreviewEvaluator.evaluate(
                pasteboardTypes: [imageType, "public.utf8-plain-text"],
                string: "Screenshot 2026-11-14.png"
            )
            XCTAssertEqual(snapshot, .empty, "Expected empty state for image/binary type \(imageType)")
            XCTAssertNil(
                ClipboardPreviewEvaluator.extractInsertablePlainText(
                    pasteboardTypes: [imageType, "public.utf8-plain-text"],
                    string: "Screenshot 2026-11-14.png"
                )
            )
        }

        // 3. Finder file copies (which also put the filename on public.utf8-plain-text) produce empty state
        let finderCopy = ClipboardPreviewEvaluator.evaluate(
            pasteboardTypes: ["public.file-url", "NSFilenamesPboardType", "public.utf8-plain-text"],
            string: "secret-keys.pem"
        )
        XCTAssertEqual(finderCopy, .empty)
        XCTAssertNil(
            ClipboardPreviewEvaluator.extractInsertablePlainText(
                pasteboardTypes: ["public.file-url", "public.utf8-plain-text"],
                string: "secret-keys.pem"
            )
        )

        // 4. Passwords / concealed / transient items produce empty state and cannot be pasted
        for concealedType in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
            "de.petermaurer.TransientPasteboardType",
            "net.antelle.keeweb"
        ] {
            let snapshot = ClipboardPreviewEvaluator.evaluate(
                pasteboardTypes: [concealedType, "public.utf8-plain-text"],
                string: "hunter2-super-secret-password"
            )
            XCTAssertEqual(snapshot, .empty, "Expected empty state for concealed type \(concealedType)")
            XCTAssertNil(
                ClipboardPreviewEvaluator.extractInsertablePlainText(
                    pasteboardTypes: [concealedType, "public.utf8-plain-text"],
                    string: "hunter2-super-secret-password"
                )
            )
        }

        // 5. Rich text copied from a browser/editor (RTF + UTF-8 plain text, no image/file/concealed) is allowed
        let richTextEval = ClipboardPreviewEvaluator.evaluate(
            pasteboardTypes: ["public.rtf", "public.utf8-plain-text"],
            string: "Copied paragraph from Notes"
        )
        XCTAssertEqual(richTextEval.previewText, "Copied paragraph from Notes")
        XCTAssertFalse(richTextEval.isTruncated)
    }

    // MARK: - 2. Multi-Display Picker Visibility & Fallback Resolution

    func testDisplayPickerVisibilityAndTargetResolution() throws {
        let builtIn = MacDisplayInfo(displayID: 1, name: "Built-in Retina Display", isMain: true)
        let studio = MacDisplayInfo(displayID: 2, name: "Studio Display", isMain: false)

        // Hidden with 0 or 1 display
        let zeroState = ControlStripState(connectedDisplays: [], selectedTargetDisplayID: 2)
        XCTAssertFalse(zeroState.shouldShowDisplayPicker)
        XCTAssertNil(zeroState.effectiveTargetDisplayID)

        let singleState = ControlStripState(connectedDisplays: [builtIn], selectedTargetDisplayID: 1)
        XCTAssertFalse(singleState.shouldShowDisplayPicker)
        XCTAssertNil(singleState.effectiveTargetDisplayID)

        // Visible with >1 displays; defaults to nil (frontmost window's display)
        let dualDefault = ControlStripState(connectedDisplays: [builtIn, studio], selectedTargetDisplayID: nil)
        XCTAssertTrue(dualDefault.shouldShowDisplayPicker)
        XCTAssertNil(dualDefault.effectiveTargetDisplayID)
        XCTAssertEqual(dualDefault.selectedDisplayLabel(in: .english), "Active Window Display")

        // Explicit display target works when connected
        let dualStudio = ControlStripState(connectedDisplays: [builtIn, studio], selectedTargetDisplayID: 2)
        XCTAssertTrue(dualStudio.shouldShowDisplayPicker)
        XCTAssertEqual(dualStudio.effectiveTargetDisplayID, 2)
        XCTAssertEqual(dualStudio.selectedDisplayLabel(in: .english), "Studio Display")

        // Falls back to nil if chosen display ID is no longer connected
        let staleSelection = ControlStripState(connectedDisplays: [builtIn, studio], selectedTargetDisplayID: 999)
        XCTAssertTrue(staleSelection.shouldShowDisplayPicker)
        XCTAssertNil(staleSelection.effectiveTargetDisplayID)

        // Legacy ControlStripState JSON without display fields decodes cleanly
        let legacyJSON = Data("""
        {"volume":0.5,"isVolumeMuted":false,"brightness":0.7,"isBrightnessAvailable":true,"isMicMuted":false}
        """.utf8)
        let decodedLegacy = try JSONDecoder().decode(ControlStripState.self, from: legacyJSON)
        XCTAssertEqual(decodedLegacy.connectedDisplays, [])
        XCTAssertNil(decodedLegacy.selectedTargetDisplayID)
        XCTAssertFalse(decodedLegacy.shouldShowDisplayPicker)
    }

    // MARK: - 3. Read-Only Next Calendar Event Selection & Permission States

    func testNextCalendarEventSelectionAndPermissionStates() {
        let base = Date(timeIntervalSince1970: 1_763_000_000)
        let endedEvent = CalendarEventCandidate(
            title: "Finished Standup",
            startDate: base.addingTimeInterval(-3600),
            endDate: base.addingTimeInterval(-600)
        )
        let canceledEvent = CalendarEventCandidate(
            title: "Canceled Sync",
            startDate: base.addingTimeInterval(300),
            endDate: base.addingTimeInterval(2100),
            isCanceled: true
        )
        let laterEvent = CalendarEventCandidate(
            title: "Design Review",
            startDate: base.addingTimeInterval(3600),
            endDate: base.addingTimeInterval(5400)
        )
        let soonestEvent = CalendarEventCandidate(
            title: "1:1 with Alex",
            startDate: base.addingTimeInterval(900),
            endDate: base.addingTimeInterval(2700)
        )

        let picked = NextCalendarEventSnapshot.selectNextEvent(
            from: [endedEvent, canceledEvent, laterEvent, soonestEvent],
            now: base
        )
        XCTAssertEqual(picked?.title, "1:1 with Alex")
        XCTAssertEqual(picked?.startDate, base.addingTimeInterval(900))
        XCTAssertEqual(picked?.isAllDay, false)

        // Denied permission never exposes an event
        let denied = NextCalendarEventSnapshot(
            permission: .denied,
            nextEvent: picked
        )
        XCTAssertEqual(denied.permission, .denied)
        XCTAssertNil(denied.nextEvent)

        let formatted = NextCalendarEventSnapshot.formattedStartTime(
            for: NextCalendarEventSummary(title: "1:1 with Alex", startDate: base.addingTimeInterval(900)),
            referenceDate: base,
            language: .english
        )
        XCTAssertFalse(formatted.isEmpty)
    }

    // MARK: - 4. End-to-End Wire Tests: Watch Privacy, Screenshot Failure/Preview, Display Target & Legacy Safety

    #if os(macOS)
    @MainActor
    func testRound02CompanionWireFlowsWatchPrivacyAndOlderClientCompatibility() async throws {
        let suiteName = "com.choclift.round02.wire.\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: suiteName)!
        defer { defaults.removePersistentDomain(forName: suiteName) }

        let longMacClipboard = String(repeating: "C", count: 340)
        let delegate = Round02WireTestDelegate(rawClipboard: longMacClipboard)
        let server = MacServerEngine(macID: "mac-round02-host", macName: "Studio Mac")
        server.delegate = delegate
        defer { server.stop() }

        // 1. Pair iPhone client
        let phoneServerEnd = server.acceptInMemoryCompanion()
        let (phoneProxy, phoneClientEnd) = InMemoryCompanionPipe.pair()
        phoneProxy.onPayload = { phoneServerEnd.send($0) }
        phoneServerEnd.onPayload = { phoneProxy.send($0) }
        phoneProxy.start()
        phoneServerEnd.start()

        let phoneClient = CompanionClientEngine(
            deviceID: "iphone-r2",
            deviceName: "iPhone 16",
            platform: .iPhone,
            userDefaults: defaults,
            storageKeyPrefix: "phone"
        )
        defer { phoneClient.disconnect() }

        phoneClient.connectInMemoryBluetooth(to: phoneClientEnd, targetName: "Studio Mac")
        for _ in 0..<50 {
            if case .awaitingPIN = phoneClient.connectionState { break }
            try await Task.sleep(for: .milliseconds(20))
        }
        phoneClient.submitPIN(server.currentPIN)
        for _ in 0..<50 where !phoneClient.connectionState.isConnected {
            try await Task.sleep(for: .milliseconds(20))
        }
        XCTAssertTrue(phoneClient.connectionState.isConnected)

        // Wait for initial dashboard sync (.clipboardPreviewUpdated + .calendarStatusUpdated)
        for _ in 0..<50 where !phoneClient.clipboardPreview.hasText || phoneClient.calendarSnapshot.nextEvent == nil {
            try await Task.sleep(for: .milliseconds(20))
        }
        XCTAssertEqual(phoneClient.clipboardPreview.previewText?.count, 280)
        XCTAssertTrue(phoneClient.clipboardPreview.isTruncated)
        XCTAssertEqual(phoneClient.calendarSnapshot.nextEvent?.title, "Product Sync")

        // 2. Pair Apple Watch client — verify Watch NEVER receives clipboard preview text
        let watchServerEnd = server.acceptInMemoryCompanion()
        let (watchProxy, watchClientEnd) = InMemoryCompanionPipe.pair()
        var watchRawFrames: [ServerMessage] = []
        var watchAcc = WireStreamAccumulator()
        watchProxy.onPayload = { watchServerEnd.send($0) }
        watchServerEnd.onPayload = { chunk in
            if let payloads = try? watchAcc.appendAndExtractPayloads(chunk) {
                for p in payloads {
                    if let msg = try? WireFrameCodec.decodePayload(ServerMessage.self, from: p) {
                        watchRawFrames.append(msg)
                    }
                }
            }
            watchProxy.send(chunk)
        }
        watchProxy.start()
        watchServerEnd.start()

        let watchClient = CompanionClientEngine(
            deviceID: "watch-r2",
            deviceName: "Apple Watch",
            platform: .appleWatch,
            userDefaults: defaults,
            storageKeyPrefix: "watch"
        )
        defer { watchClient.disconnect() }

        watchClient.connectInMemoryBluetooth(to: watchClientEnd, targetName: "Studio Mac")
        for _ in 0..<50 {
            if case .awaitingPIN = watchClient.connectionState { break }
            try await Task.sleep(for: .milliseconds(20))
        }
        watchClient.submitPIN(server.currentPIN)
        for _ in 0..<50 where !watchClient.connectionState.isConnected {
            try await Task.sleep(for: .milliseconds(20))
        }
        XCTAssertTrue(watchClient.connectionState.isConnected)

        // Broadcast updated clipboard from server — phone updates, Watch stays empty & receives zero clipboard frames
        let updatedPreview = ClipboardPreviewEvaluator.evaluate(
            pasteboardTypes: ["public.utf8-plain-text"],
            string: "Secret-free note on Mac"
        )
        server.broadcastClipboardPreview(updatedPreview)
        try await Task.sleep(for: .milliseconds(60))

        XCTAssertEqual(phoneClient.clipboardPreview.previewText, "Secret-free note on Mac")
        XCTAssertEqual(watchClient.clipboardPreview, .empty)
        XCTAssertFalse(
            watchRawFrames.contains {
                if case .clipboardPreviewUpdated = $0 { return true }
                return false
            }
        )

        // Watch "Paste Clipboard" button triggers Mac clipboard paste without exposing text
        watchClient.pasteMacClipboard()
        for _ in 0..<50 where delegate.pasteCount < 1 {
            try await Task.sleep(for: .milliseconds(20))
        }
        XCTAssertEqual(delegate.pasteCount, 1)

        // 3. Connect an older client (never sends .requestCompanionDashboard) — must not disconnect or receive unsolicited dashboard broadcasts
        let legacyPipe = server.acceptInMemoryCompanion()
        var legacyMessages: [ServerMessage] = []
        var legacyAcc = WireStreamAccumulator()
        legacyPipe.onPayload = { chunk in
            if let payloads = try? legacyAcc.appendAndExtractPayloads(chunk) {
                for p in payloads {
                    if let msg = try? WireFrameCodec.decodePayload(ServerMessage.self, from: p) {
                        legacyMessages.append(msg)
                    }
                }
            }
        }
        legacyPipe.start()
        legacyPipe.send(
            try WireFrameCodec.encode(
                ClientMessage.hello(
                    protocolVersion: ChocliftDefaults.protocolVersion,
                    deviceID: "legacy-phone",
                    deviceName: "Older iPhone",
                    platform: .iPhone,
                    savedAuthToken: nil
                )
            )
        )
        legacyPipe.send(
            try WireFrameCodec.encode(
                ClientMessage.submitPIN(
                    pin: server.currentPIN,
                    deviceID: "legacy-phone",
                    deviceName: "Older iPhone",
                    platform: .iPhone
                )
            )
        )
        // Also send an unknown post-auth ClientMessage frame to verify MacServerEngine ignores it without disconnecting
        let unknownClientPayload = Data(#"{"futureClientCommand":{"flag":true}}"#.utf8)
        var lengthBE = UInt32(unknownClientPayload.count).bigEndian
        var unknownClientFrame = Data(capacity: 4 + unknownClientPayload.count)
        withUnsafeBytes(of: &lengthBE) { unknownClientFrame.append(contentsOf: $0) }
        unknownClientFrame.append(unknownClientPayload)
        legacyPipe.send(unknownClientFrame)

        server.broadcastClipboardPreview(updatedPreview)
        server.broadcastCalendarStatus(delegate.calendarSnapshot)
        legacyPipe.send(try WireFrameCodec.encode(ClientMessage.ping(timestamp: Date().timeIntervalSince1970)))
        try await Task.sleep(for: .milliseconds(60))

        XCTAssertTrue(legacyMessages.contains { if case .pong = $0 { return true }; return false })
        XCTAssertFalse(legacyMessages.contains { if case .clipboardPreviewUpdated = $0 { return true }; return false })
        XCTAssertFalse(legacyMessages.contains { if case .calendarStatusUpdated = $0 { return true }; return false })

        // 4. Screenshot failure (missing Screen Recording permission) -> existing-style failure toast on phone
        delegate.simulateMissingScreenRecording = true
        phoneClient.captureMainDisplayScreenshot()
        for _ in 0..<50 where phoneClient.isCapturingScreenshot {
            try await Task.sleep(for: .milliseconds(20))
        }
        XCTAssertNil(phoneClient.latestScreenshotPreview)
        XCTAssertEqual(phoneClient.lastFeedback?.success, false)
        XCTAssertTrue(phoneClient.lastFeedback?.detail?.contains("Screen Recording") ?? false)

        // 5. Screenshot success -> thumbnail preview populated on phone
        delegate.simulateMissingScreenRecording = false
        phoneClient.captureMainDisplayScreenshot()
        for _ in 0..<50 where phoneClient.latestScreenshotPreview == nil {
            try await Task.sleep(for: .milliseconds(20))
        }
        XCTAssertEqual(phoneClient.latestScreenshotPreview?.success, true)
        XCTAssertEqual(phoneClient.latestScreenshotPreview?.fileName, "Choclift Screenshot Test.png")
        XCTAssertNotNil(phoneClient.latestScreenshotPreview?.previewJPEGData)

        // 6. Display target selection & Calendar open action
        phoneClient.setTargetDisplay(displayID: 2)
        phoneClient.openCalendarOnMac()
        for _ in 0..<50 where !delegate.didOpenCalendar {
            try await Task.sleep(for: .milliseconds(20))
        }
        XCTAssertEqual(delegate.selectedDisplayID, 2)
        XCTAssertTrue(delegate.didOpenCalendar)
    }
    #endif
}

#if os(macOS)
@MainActor
private final class Round02WireTestDelegate: MacServerEngineDelegate {
    var profile = ChocliftDefaults.makeDefaultProfile()
    var rawClipboard: String
    var pasteCount = 0
    var simulateMissingScreenRecording = false
    var selectedDisplayID: UInt32?
    var didOpenCalendar = false
    let calendarSnapshot = NextCalendarEventSnapshot(
        permission: .authorized,
        nextEvent: NextCalendarEventSummary(
            title: "Product Sync",
            startDate: Date(timeIntervalSince1970: 1_763_005_000)
        )
    )

    init(rawClipboard: String) {
        self.rawClipboard = rawClipboard
    }

    func serverCurrentProfile() -> ChocliftWorkspaceProfile { profile }
    func serverCurrentRecentApps() -> [RecentAppEntry] { [] }
    func serverFrontmostBundleID() -> String? { nil }
    func serverTextInputState() -> (isEditing: Bool, appName: String?) { (false, nil) }
    func serverIsAccessibilityGranted() -> Bool { true }
    func serverCurrentOrcaStatus() -> OrcaTaskStatusSnapshot? { nil }
    func serverIcons(for bundleIDs: [String]) -> [String: Data] { [:] }
    func serverDidUpdatePairedDevices(_ devices: [PairedDeviceRecord]) {}

    func serverDidReceiveAuthenticatedMessage(
        _ message: ClientMessage,
        from device: PairedDeviceRecord,
        reply: @escaping @MainActor (ServerMessage) -> Void
    ) {
        switch message {
        case .requestControlStripState:
            let displays = [
                MacDisplayInfo(displayID: 1, name: "Built-in", isMain: true),
                MacDisplayInfo(displayID: 2, name: "External", isMain: false)
            ]
            reply(.controlStripStateUpdated(ControlStripState(
                connectedDisplays: displays,
                selectedTargetDisplayID: selectedDisplayID
            )))

        case .requestCompanionDashboard:
            if device.platform != .appleWatch {
                let snap = ClipboardPreviewEvaluator.evaluate(
                    pasteboardTypes: ["public.utf8-plain-text"],
                    string: rawClipboard
                )
                reply(.clipboardPreviewUpdated(snap))
            }
            reply(.calendarStatusUpdated(calendarSnapshot))

        case .pasteMacClipboard:
            pasteCount += 1
            reply(.actionFeedback(success: true, title: "Pasted Clipboard", detail: nil))

        case .captureMainDisplayScreenshot:
            if simulateMissingScreenRecording {
                reply(.screenshotCaptured(.failed(
                    errorMessage: "Screen Recording permission required — enable Choclift in System Settings"
                )))
            } else {
                reply(.screenshotCaptured(.succeeded(
                    fileName: "Choclift Screenshot Test.png",
                    previewJPEGData: Data([0xFF, 0xD8, 0xFF, 0xD9])
                )))
            }

        case .setTargetDisplay(let displayID):
            selectedDisplayID = displayID
            reply(.controlStripStateUpdated(ControlStripState(
                connectedDisplays: [
                    MacDisplayInfo(displayID: 1, name: "Built-in", isMain: true),
                    MacDisplayInfo(displayID: 2, name: "External", isMain: false)
                ],
                selectedTargetDisplayID: selectedDisplayID
            )))

        case .openCalendarApp:
            didOpenCalendar = true
            reply(.actionFeedback(success: true, title: "Calendar", detail: "Opened Calendar"))

        default:
            break
        }
    }
}
